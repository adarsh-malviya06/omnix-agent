"""
InventoryAlert model — persistent alerts for low stock, out of stock, and stockout risk.
"""

from datetime import datetime
from typing import TYPE_CHECKING, Optional
from sqlalchemy import Boolean, DateTime, ForeignKey, Integer, String, Text
from sqlalchemy.orm import Mapped, mapped_column, relationship

from omnix.db.base import Base, TimestampMixin

if TYPE_CHECKING:
    from omnix.db.models.product import Product
    from omnix.db.models.location import Location


class InventoryAlert(TimestampMixin, Base):
    """
    Persistent inventory alert generated by inventory monitoring scans.
    Tracks alert status, severity, deduplication, and resolution audit trail.
    """

    __tablename__ = "inventory_alerts"

    id: Mapped[int] = mapped_column(primary_key=True, index=True)
    organization_id: Mapped[Optional[int]] = mapped_column(
        ForeignKey("organizations.id", ondelete="CASCADE"), nullable=True, index=True
    )
    product_id: Mapped[int] = mapped_column(
        ForeignKey("products.id", ondelete="CASCADE"), nullable=False, index=True
    )
    location_id: Mapped[int] = mapped_column(
        ForeignKey("locations.id", ondelete="CASCADE"), nullable=False, index=True
    )
    alert_type: Mapped[str] = mapped_column(
        String(50), nullable=False, index=True,
        comment="LOW_STOCK, OUT_OF_STOCK, HIGH_STOCKOUT_RISK, REORDER_RECOMMENDED"
    )
    severity: Mapped[str] = mapped_column(
        String(20), nullable=False, default="WARNING",
        comment="INFO, WARNING, CRITICAL"
    )
    title: Mapped[str] = mapped_column(String(200), nullable=False)
    message: Mapped[str] = mapped_column(Text, nullable=False)
    current_stock: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    threshold_value: Mapped[int] = mapped_column(Integer, nullable=False, default=0)

    # Resolution lifecycle
    is_resolved: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False, index=True)
    resolved_at: Mapped[Optional[datetime]] = mapped_column(DateTime, nullable=True)
    resolved_by: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    resolution_notes: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)

    # Relationships
    product: Mapped["Product"] = relationship("Product")
    location: Mapped["Location"] = relationship("Location")

    def __repr__(self) -> str:
        return f"<InventoryAlert id={self.id} type={self.alert_type} product_id={self.product_id} resolved={self.is_resolved}>"
